/**
 * Regenerates docs/GAME_TRACKER.md from @playverse/game-catalog so the tracker
 * can never drift from the source of truth. Run: npm run catalog:docs
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CATEGORIES, GAMES } from '@playverse/game-catalog';
import { RUNTIME_KEYS } from '@playverse/game-runtime';

const categoryName = new Map<string, string>(CATEGORIES.map((c) => [c.slug, c.name]));
const implemented = new Set<string>(RUNTIME_KEYS);
const devices = (d: string[]) => d.map((x) => x[0]).join('');

const status = (runtimeKey?: string) =>
  runtimeKey && implemented.has(runtimeKey) ? 'Module implemented (not yet launchable)' : 'Planned';

const batches = [...new Set(GAMES.map((g) => g.batch))].sort((a, b) => a - b);
const lines: string[] = [
  '# Game implementation & licensing tracker',
  '',
  '> Generated by `npm run catalog:docs` from `packages/game-catalog`. Do not edit by hand.',
  '',
  `**Catalog entries:** ${GAMES.length} · **Categories:** ${CATEGORIES.length} · **Runtime modules implemented:** ${implemented.size} · **Publicly playable:** 0`,
  '',
  'Status definitions:',
  '',
  '- **Planned** — catalog entry only; no code yet. Shown publicly as *Coming soon*.',
  '- **Module implemented** — a runtime module exists and is unit-tested, but the player page / launch flow is not yet available.',
  '- **Published** — launch flow tested end-to-end and published by an admin. (None yet.)',
  '',
  'All entries are original in-house implementations (`ORIGINAL` license): no third-party code, artwork or trademarked names.',
  'Devices: D = desktop, T = tablet, M = mobile.',
  '',
];

for (const batch of batches) {
  const games = GAMES.filter((g) => g.batch === batch);
  lines.push(`## Batch ${batch} (${games.length} games)`, '', '| # | Game | Category | Difficulty | Engine | Devices | Scores | Mode | License | Status |', '|---|---|---|---|---|---|---|---|---|---|');
  games.forEach((g, i) => {
    lines.push(
      `| ${i + 1} | ${g.title} (\`${g.slug}\`) | ${categoryName.get(g.category)} | ${g.difficulty} | ${g.engine} | ${devices(g.devices)} | ${g.supportsScores ? 'Yes' : 'No'} | ${g.multiplayerMode ?? 'single'} | ${g.license} | ${status(g.runtimeKey)} |`,
    );
  });
  lines.push('');
}

const target = resolve(import.meta.dirname, '../docs/GAME_TRACKER.md');
writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${target} (${GAMES.length} games)`);
