/**
 * Regenerates docs/GAME_TRACKER.md from @suresh/game-catalog so the tracker
 * can never drift from the source of truth. Run: npm run catalog:docs
 *
 * Verification columns come from the code and, when present, the latest browser
 * smoke run in reports/games-smoke (see docs/GAME_PUBLISHING.md). Whether a game is
 * *published* is per-deployment database state, so it is deliberately not listed here.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { CATEGORIES, GAMES } from '@suresh/game-catalog';
import { RUNTIME_KEYS } from '@suresh/game-runtime';
import { GAMES_DIR, RESULTS_DIR, RUN_FILE, SMOKE_PROJECTS, type SmokeResult, type SmokeRun } from '../tests/e2e/smoke/paths';

const categoryName = new Map<string, string>(CATEGORIES.map((c) => [c.slug, c.name]));
const implemented = new Set<string>(RUNTIME_KEYS);
const devices = (d: string[]) => d.map((x) => x[0]).join('');

/** Games with dedicated rules tests: a test file in their folder, or imported by a shared suite. */
function gamesWithLogicTests(): Set<string> {
  const covered = new Set<string>();
  for (const entry of readdirSync(GAMES_DIR, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (readdirSync(path.join(GAMES_DIR, entry.name)).some((f) => f.endsWith('.test.ts'))) covered.add(entry.name);
    } else if (entry.name.endsWith('.test.ts')) {
      const source = readFileSync(path.join(GAMES_DIR, entry.name), 'utf8');
      for (const match of source.matchAll(/from '\.\/([a-z0-9-]+)\//g)) covered.add(match[1]!);
    }
  }
  return covered;
}

/** Results of the latest smoke run, keyed by `<project>:<slug>`. */
function latestSmokeRun(): { run: SmokeRun; results: Map<string, SmokeResult> } | null {
  if (!existsSync(RUN_FILE)) return null;
  const run = JSON.parse(readFileSync(RUN_FILE, 'utf8')) as SmokeRun;
  const results = new Map<string, SmokeResult>();
  for (const project of Object.values(SMOKE_PROJECTS)) {
    const dir = path.join(RESULTS_DIR, project);
    if (!existsSync(dir)) continue;
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.json'))) {
      const result = JSON.parse(readFileSync(path.join(dir, file), 'utf8')) as SmokeResult;
      if (result.runId === run.runId) results.set(`${project}:${result.slug}`, result);
    }
  }
  return { run, results };
}

const logicTests = gamesWithLogicTests();
const smoke = latestSmokeRun();
const smokeDate = smoke ? smoke.run.startedAt.slice(0, 10) : null;
const passedOn = (project: string) =>
  smoke ? [...smoke.results.entries()].filter(([key, r]) => key.startsWith(`${project}:`) && r.status === 'passed').length : 0;
const mobileGames = GAMES.filter((g) => g.devices.includes('MOBILE')).length;

const browserCell = (project: string, slug: string, applicable = true) => {
  if (!applicable) return 'n/a';
  const result = smoke?.results.get(`${project}:${slug}`);
  if (!result) return '—';
  return result.status === 'passed' ? '✅' : `❌ ${result.status}`;
};

const batches = [...new Set(GAMES.map((g) => g.batch))].sort((a, b) => a - b);
const lines: string[] = [
  '# Game implementation & licensing tracker',
  '',
  '> Generated by `npm run catalog:docs` from `packages/game-catalog`. Do not edit by hand.',
  '',
  `**Catalog entries:** ${GAMES.length} · **Categories:** ${CATEGORIES.length} · **Runtime modules implemented:** ${implemented.size} · ` +
    `**Dedicated rules tests:** ${GAMES.filter((g) => logicTests.has(g.slug)).length} · ` +
    (smoke
      ? `**Browser smoke test (${smokeDate}, ${smoke.run.webMode ?? 'dev server'}):** desktop ${passedOn(SMOKE_PROJECTS.desktop)}/${implemented.size} passed, ` +
        `mobile ${passedOn(SMOKE_PROJECTS.mobile)}/${mobileGames} passed`
      : '**Browser smoke test:** not run yet'),
  '',
  'Verification columns:',
  '',
  '- **Module** — a runtime module exists in `packages/game-runtime/src/games/<slug>`. Every module passes the contract test',
  '  (full lifecycle with fuzzed keyboard/pointer/button input, pause/resume/restart, resize, cleanup and listener-leak checks)',
  '  and the rules test (no `Math.random`, storage, cookies, network, navigation, `eval` or inline handlers).',
  '- **Rules tests** — dedicated unit tests for the game logic (move generation, scoring, solvability of generated puzzles…).',
  '- **Desktop / Mobile** — result of the latest launch-flow smoke test in Chromium through the real player page and API',
  '  (`npm run test:e2e:games`): load, start a server session, play (keyboard + pointer on desktop; taps, swipe and',
  '  on-screen controls on an emulated touch phone), end the round, and no game, page or console errors.',
  '  Mobile is `n/a` for desktop-only games.',
  '',
  'Publishing is per deployment: `npm run games:publish` marks only the games that passed the latest run (desktop, and',
  'mobile where supported) as `PUBLISHED`; everything else stays *Coming soon*. See `docs/GAME_PUBLISHING.md`.',
  '',
  'All entries are original in-house implementations (`ORIGINAL` license): no third-party code, artwork or trademarked names.',
  'Engines: CANVAS = 2D canvas game loop; DOM = HTML/CSS-rendered board, card, puzzle and word games.',
  'Devices: D = desktop, T = tablet, M = mobile.',
  '',
];

for (const batch of batches) {
  const games = GAMES.filter((g) => g.batch === batch);
  lines.push(
    `## Batch ${batch} (${games.length} games)`,
    '',
    '| # | Game | Category | Difficulty | Engine | Devices | Scores | Mode | License | Module | Rules tests | Desktop | Mobile |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|---|',
  );
  games.forEach((g, i) => {
    const hasModule = Boolean(g.runtimeKey && implemented.has(g.runtimeKey));
    lines.push(
      `| ${i + 1} | ${g.title} (\`${g.slug}\`) | ${categoryName.get(g.category)} | ${g.difficulty} | ${g.engine} | ${devices(g.devices)} | ` +
        `${g.supportsScores ? 'Yes' : 'No'} | ${g.multiplayerMode ?? 'single'} | ${g.license} | ${hasModule ? '✅' : 'Planned'} | ` +
        `${logicTests.has(g.slug) ? '✅' : '—'} | ${browserCell(SMOKE_PROJECTS.desktop, g.slug)} | ` +
        `${browserCell(SMOKE_PROJECTS.mobile, g.slug, g.devices.includes('MOBILE'))} |`,
    );
  });
  lines.push('');
}

const target = path.resolve(import.meta.dirname, '../docs/GAME_TRACKER.md');
writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${target} (${GAMES.length} games)`);
