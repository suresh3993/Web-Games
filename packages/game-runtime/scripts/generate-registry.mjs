// Regenerates src/registry.generated.ts from the folders in src/games.
// Each folder name is the game's runtime key; each module default-exports its GameModule
// (Snake, the original reference module, uses a named export).
// Run: npm run registry -w @suresh/game-runtime
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const games = readdirSync(join(root, 'games'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(root, 'games', d.name, 'index.ts')))
  .map((d) => d.name)
  .sort();

const lines = games.map((key) =>
  key === 'snake'
    ? `  snake: () => import('./games/snake/index').then((m) => m.snakeGame),`
    : `  '${key}': () => import('./games/${key}/index').then((m) => m.default),`,
);

writeFileSync(
  join(root, 'registry.generated.ts'),
  `// AUTO-GENERATED by scripts/generate-registry.mjs — do not edit by hand.
import type { GameModuleLoader } from './interfaces/game-module';

export const generatedRegistry = {
${lines.join('\n')}
} satisfies Record<string, GameModuleLoader>;
`,
);
console.log(`registry: ${games.length} games`);
